#!/usr/bin/env node
/**
 * mysql-to-postgres.mjs — Convierte el esquema MySQL/MariaDB del dashboard
 * (`database/lasmunecasderamon.sql`, dump de phpMyAdmin) a DDL PostgreSQL.
 *
 * Uso:
 *   node scripts/mysql-to-postgres.mjs                 # genera el .postgres.sql
 *   node scripts/mysql-to-postgres.mjs --report        # solo informe, sin escribir
 *
 * Salida:
 *   database/lasmunecasderamon.postgres.sql
 *
 * Decisiones de conversión (ver logs/Migracion-PostgreSQL-Analisis.md, Anexo A):
 *   - tinyint/tinyint(1) -> smallint   (se preservan los 1/0 que usa el código)
 *   - datetime/timestamp -> timestamp  (sin zona, como el original)
 *   - enum(...)          -> varchar(n) + CHECK
 *   - longtext           -> text
 *   - int                -> integer
 *   - decimal(p,s)       -> numeric(p,s)
 *   - AUTO_INCREMENT     -> GENERATED BY DEFAULT AS IDENTITY + RESTART WITH
 *   - ON UPDATE CURRENT_TIMESTAMP -> trigger BEFORE UPDATE
 *   - COMMENT            -> COMMENT ON COLUMN / TABLE
 *   - ADD KEY / UNIQUE KEY -> CREATE INDEX / ADD CONSTRAINT UNIQUE
 *   - Se descartan backticks, CHARACTER SET, COLLATE, ENGINE y los comentarios
 *     versionados de MySQL ( SET + BEGIN/COMMIT + directivas entre exclamación )
 *
 * Correcciones del Anexo A aplicadas automáticamente:
 *   - FIX-1: anticipos.entregado_por  int -> varchar(36) + FK a usuarios(id_usuario)
 *   - FIX-2: backups recibe PRIMARY KEY (id_backup)
 *   - FIX-3: detalle_pedidos.habitacion_id -> se deja UNA sola FK (SET NULL)
 *   - FIX-4: se eliminan índices exactamente duplicados sobre las mismas columnas
 */
import fs from 'fs';
import path from 'path';

const SRC = path.resolve('database/lasmunecasderamon.sql');
const OUT = path.resolve('database/lasmunecasderamon.postgres.sql');
const REPORT_ONLY = process.argv.includes('--report');

const warnings = [];
const stats = {
  tables: 0,
  columns: 0,
  inserts: 0,
  rows: 0,
  indexes: 0,
  unique: 0,
  primaryKeys: 0,
  foreignKeys: 0,
  checks: 0,
  comments: 0,
  identities: 0,
  skipped: []
};
const warn = msg => warnings.push(msg);

/* ------------------------------------------------------------------ *
 * Utilidades de parseo
 * ------------------------------------------------------------------ */

const ident = name => String(name).replace(/`/g, '');

/** Divide un script SQL en sentencias, respetando comillas simples y backticks. */
function splitStatements(sql) {
  const out = [];
  let buf = '';
  let inStr = false;
  let inBacktick = false;
  const lines = sql.split(/\r?\n/);

  for (const rawLine of lines) {
    const line = rawLine;
    // Saltar comentarios de línea completos
    if (!inStr && !inBacktick && /^\s*--/.test(line)) continue;
    if (!inStr && !inBacktick && /^\s*\/\*/.test(line)) continue;

    for (let i = 0; i < line.length; i++) {
      const ch = line[i];
      if (inStr) {
        if (ch === '\\') {
          buf += ch + (line[i + 1] ?? '');
          i++;
          continue;
        }
        if (ch === "'") {
          inStr = false;
          buf += ch;
          continue;
        }
        buf += ch;
        continue;
      }
      if (inBacktick) {
        if (ch === '`') inBacktick = false;
        buf += ch;
        continue;
      }
      if (ch === "'") {
        inStr = true;
        buf += ch;
        continue;
      }
      if (ch === '`') {
        inBacktick = true;
        buf += ch;
        continue;
      }
      if (ch === ';') {
        const stmt = buf.trim();
        if (stmt) out.push(stmt);
        buf = '';
        continue;
      }
      buf += ch;
    }
    buf += '\n';
  }
  const tail = buf.trim();
  if (tail) out.push(tail);
  return out;
}

/** Extrae el primer token de tipo respetando paréntesis balanceados. */
function readType(text) {
  const m = /^([a-zA-Z]+)\s*\(/.exec(text);
  if (!m) {
    const m2 = /^([a-zA-Z]+)/.exec(text);
    return { base: m2 ? m2[1].toLowerCase() : '', args: null, rest: text.slice(m2 ? m2[1].length : 0) };
  }
  const base = m[1].toLowerCase();
  let depth = 0;
  let end = -1;
  for (let i = m[0].length - 1; i < text.length; i++) {
    if (text[i] === '(') depth++;
    else if (text[i] === ')') {
      depth--;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  if (end === -1) return { base, args: null, rest: text.slice(m[0].length) };
  return { base, args: text.slice(text.indexOf('(') + 1, end), rest: text.slice(end + 1) };
}

/** Decodifica un literal de cadena MySQL (incluye escapes con backslash). */
function decodeMysqlString(raw) {
  const MAP = { '0': '\0', b: '\b', n: '\n', r: '\r', t: '\t', Z: '\x1a', '\\': '\\', "'": "'", '"': '"' };
  let out = '';
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] === '\\' && i + 1 < raw.length) {
      const n = raw[i + 1];
      out += Object.prototype.hasOwnProperty.call(MAP, n) ? MAP[n] : n;
      i++;
    } else {
      out += raw[i];
    }
  }
  return out;
}

/** Codifica un valor para PostgreSQL (standard_conforming_strings = on). */
function encodePgString(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

/** Convierte los literales de cadena de un fragmento de MySQL a PostgreSQL. */
function convertStringLiterals(fragment) {
  let out = '';
  let i = 0;
  while (i < fragment.length) {
    if (fragment[i] !== "'") {
      out += fragment[i];
      i++;
      continue;
    }
    let raw = '';
    i++;
    while (i < fragment.length) {
      if (fragment[i] === '\\') {
        raw += fragment[i] + (fragment[i + 1] ?? '');
        i += 2;
        continue;
      }
      if (fragment[i] === "'") {
        if (fragment[i + 1] === "'") {
          raw += "''";
          i += 2;
          continue;
        }
        i++;
        break;
      }
      raw += fragment[i];
      i++;
    }
    out += encodePgString(decodeMysqlString(raw));
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * Mapeo de tipos
 * ------------------------------------------------------------------ */

function mapColumnType(col, table) {
  const { base, args } = col;

  if (base === 'enum') {
    const values = String(args)
      .split(',')
      .map(v => decodeMysqlString(v.trim().replace(/^'|'$/g, '')));
    const width = Math.max(...values.map(v => v.length), 8) + 4;
    stats.checks++;
    return { pgType: `varchar(${width})`, check: values };
  }
  if (base === 'tinyint' || base === 'smallint') return { pgType: 'smallint', numeric: true };
  if (base === 'mediumint' || base === 'int' || base === 'integer') return { pgType: 'integer', numeric: true };
  if (base === 'bigint') return { pgType: 'bigint', numeric: true };
  if (base === 'decimal' || base === 'numeric') return { pgType: `numeric(${args})`, numeric: true };
  if (base === 'float') return { pgType: 'real', numeric: true };
  if (base === 'double') return { pgType: 'double precision', numeric: true };
  if (base === 'datetime' || base === 'timestamp') return { pgType: 'timestamp' };
  if (base === 'date') return { pgType: 'date' };
  if (base === 'time') return { pgType: 'time' };
  if (base === 'longtext' || base === 'mediumtext' || base === 'text') return { pgType: 'text' };
  if (base === 'varchar' || base === 'char') return { pgType: `${base}(${args})` };
  if (base === 'json') return { pgType: 'jsonb' };

  warn(`Tipo no mapeado en ${table}: ${base}(${args ?? ''}) -> text (revisar)`);
  return { pgType: 'text' };
}

/** Convierte un fragmento de DDL reemplazando solo identificadores entre backticks. */
function deBacktick(text) {
  return convertStringLiterals(text.replace(/`([^`]+)`/g, '$1'));
}

/** Devuelve el índice del paréntesis de cierre que corresponde al de apertura dado. */
function findMatchingParen(text, openIndex) {
  let depth = 0;
  let inStr = false;
  let inBacktick = false;
  for (let i = openIndex; i < text.length; i++) {
    const ch = text[i];
    if (inStr) {
      if (ch === '\\') {
        i++;
        continue;
      }
      if (ch === "'") inStr = false;
      continue;
    }
    if (inBacktick) {
      if (ch === '`') inBacktick = false;
      continue;
    }
    if (ch === "'") {
      inStr = true;
      continue;
    }
    if (ch === '`') {
      inBacktick = true;
      continue;
    }
    if (ch === '(') depth++;
    else if (ch === ')') {
      depth--;
      if (depth === 0) return i;
    }
  }
  return -1;
}

/* ------------------------------------------------------------------ *
 * CREATE TABLE
 * ------------------------------------------------------------------ */

function convertCreateTable(stmt) {
  const head = /CREATE TABLE\s+(?:IF NOT EXISTS\s+)?`?([^`\s(]+)`?\s*\(/i.exec(stmt);
  if (!head) {
    warn('CREATE TABLE no reconocido, se omite');
    return null;
  }
  const table = ident(head[1]);
  const openParen = head.index + head[0].length - 1;
  const bodyEnd = findMatchingParen(stmt, openParen);
  if (bodyEnd === -1) {
    warn(`No se pudo cerrar el paréntesis de ${table}`);
    return null;
  }
  const body = stmt.slice(openParen + 1, bodyEnd);
  const options = stmt.slice(bodyEnd + 1);

  const columns = [];
  const checks = [];
  const comments = [];
  let inlinePk = [];

  for (const line of body.split(/\r?\n/)) {
    // Cada línea del cuerpo puede terminar en coma (separador de columna del dump)
    const t = line.trim().replace(/,\s*$/, '');
    if (!t) continue;

    if (/^PRIMARY KEY/i.test(t)) {
      inlinePk.push(t);
      continue;
    }
    if (/^(UNIQUE KEY|KEY|FULLTEXT|SPATIAL|CONSTRAINT|INDEX)/i.test(t)) {
      warn(`Restricción inline ignorada en ${table}: ${t.slice(0, 80)}`);
      continue;
    }

    const m = /^`([^`]+)`\s+(.*)$/.exec(t);
    if (!m) {
      warn(`Línea no reconocida en ${table}: ${t.slice(0, 80)}`);
      continue;
    }

    const name = ident(m[1]);
    let attrs = m[2].trim();

    const commentMatch = /\s*COMMENT\s+'((?:[^'\\]|\\.)*)'\s*$/i.exec(attrs);
    if (commentMatch) {
      comments.push({ column: name, text: decodeMysqlString(commentMatch[1]) });
      attrs = attrs.slice(0, commentMatch.index).trim();
      stats.comments++;
    }

    const col = readType(attrs);
    const mapped = mapColumnType(col, table);

    let tail = col.rest;
    const hasOnUpdate = /ON\s+UPDATE\s+CURRENT_TIMESTAMP/i.test(tail);
    tail = tail.replace(/CHARACTER\s+SET\s+\w+/gi, '');
    tail = tail.replace(/COLLATE\s+\w+/gi, '');
    tail = tail.replace(/ON\s+UPDATE\s+CURRENT_TIMESTAMP(\(\d*\))?/gi, '');
    if (hasOnUpdate) onUpdateColumns.push({ table, column: name });

    const isAutoIncrement = /AUTO_INCREMENT/i.test(tail);
    tail = tail.replace(/AUTO_INCREMENT/gi, '');

    // FIX-1: anticipos.entregado_por guarda un UUID de usuario, no un entero
    if (table === 'anticipos' && name === 'entregado_por' && col.base === 'int') {
      mapped.pgType = 'varchar(36)';
      mapped.numeric = false;
      warn('FIX-1 aplicado: anticipos.entregado_por int -> varchar(36)');
    }

    tail = tail.replace(/\s+/g, ' ').trim();

    if (mapped.numeric) {
      tail = tail.replace(/DEFAULT\s+'(-?\d+(?:\.\d+)?)'/gi, 'DEFAULT $1');
    }

    if (isAutoIncrement) {
      tail += ' GENERATED BY DEFAULT AS IDENTITY';
      stats.identities++;
    }

    const def = `${name} ${mapped.pgType}${tail ? ' ' + tail : ''}`.replace(/\s+/g, ' ').trim();
    columns.push(def);
    stats.columns++;

    if (mapped.check) checks.push({ column: name, values: mapped.check });
  }

  // FIX-2: backups no tiene PK en el dump de MySQL
  if (table === 'backups' && inlinePk.length === 0) {
    inlinePk = ['PRIMARY KEY (`id_backup`)'];
    warn('FIX-2 aplicado: backups recibe PRIMARY KEY (id_backup)');
  }

  // La PK va al final, como es convencional en PostgreSQL
  const lines = [...columns, ...inlinePk.map(p => deBacktick(p))].filter(Boolean);
  let out = `CREATE TABLE ${table} (\n  ${deBacktick(lines.join(',\n  '))}\n);`;

  for (const c of checks) {
    const values = c.values.map(v => encodePgString(v)).join(', ');
    out += `\nALTER TABLE ${table} ADD CONSTRAINT chk_${table}_${c.column} CHECK (${c.column} IN (${values}));`;
    if (c.values.some(v => v !== v.toLowerCase())) {
      warn(
        `OJO ${table}.${c.column}: ENUM con valores sensibles a mayúsculas (${c.values.join(', ')}). ` +
          'En MySQL el ENUM era case-insensitive; el CHECK de PostgreSQL es case-sensitive.'
      );
    }
  }

  const tableComment = /COMMENT\s*=\s*'((?:[^'\\]|\\.)*)'/i.exec(options);
  if (tableComment) {
    out += `\nCOMMENT ON TABLE ${table} IS ${encodePgString(decodeMysqlString(tableComment[1]))};`;
    stats.comments++;
  }
  for (const c of comments) {
    out += `\nCOMMENT ON COLUMN ${table}.${c.column} IS ${encodePgString(c.text)};`;
  }

  stats.tables++;
  return out;
}

/* ------------------------------------------------------------------ *
 * INSERT
 * ------------------------------------------------------------------ */

function convertInsert(stmt) {
  const idx = stmt.search(/\bVALUES\b/i);
  if (idx === -1) {
    warn(`INSERT sin VALUES, se omite: ${stmt.slice(0, 60)}`);
    return null;
  }
  const head = deBacktick(stmt.slice(0, idx));
  let values = convertStringLiterals(stmt.slice(idx + 6));
  // Match the existing PostgreSQL import's sentinel for unknown creation dates.
  // The original dump remains available; never interpret the sentinel as a real date.
  const zeroDates = (values.match(/'0000-00-00 00:00:00'/g) || []).length;
  if (zeroDates) warn(`${head.trim()}: ${zeroDates} fechas cero convertidas a 1970-01-01 (fecha desconocida)`);
  values = values.replace(/'0000-00-00 00:00:00'/g, "'1970-01-01 00:00:00'");

  const table = /INSERT\s+INTO\s+(\w+)/i.exec(head);
  const rows = (values.match(/\)\s*,?\s*(?=\()/g) || []).length + 1;
  if (table) stats.rows += rows;
  stats.inserts++;

  return `${head}VALUES${values};`;
}

/* ------------------------------------------------------------------ *
 * ALTER TABLE
 * ------------------------------------------------------------------ */

/** Divide un cuerpo de ALTER TABLE en cláusulas, respetando paréntesis y comillas. */
function splitAlterClauses(body) {
  const clauses = [];
  let buf = '';
  let depth = 0;
  let inStr = false;

  for (let i = 0; i < body.length; i++) {
    const ch = body[i];
    if (inStr) {
      buf += ch;
      if (ch === '\\') {
        buf += body[i + 1] ?? '';
        i++;
      } else if (ch === "'") inStr = false;
      continue;
    }
    if (ch === "'") {
      inStr = true;
      buf += ch;
      continue;
    }
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) {
      clauses.push(buf.trim());
      buf = '';
      continue;
    }
    buf += ch;
  }
  if (buf.trim()) clauses.push(buf.trim());
  return clauses;
}

const seenIndexes = new Set();
const seenFks = new Set();
const onUpdateColumns = [];

function convertAlter(stmt) {
  const head = /^ALTER\s+TABLE\s+`?([^`\s]+)`?/i.exec(stmt.trim());
  if (!head) {
    warn(`ALTER TABLE no reconocido: ${stmt.slice(0, 60)}`);
    return [];
  }
  const table = ident(head[1]);
  const body = stmt.slice(head[0].length).trim();

  if (/^\s*MODIFY\b/i.test(body)) {
    const col = /MODIFY\s+`?([^`\s]+)`?/i.exec(body);
    const next = /AUTO_INCREMENT\s*=\s*(\d+)/i.exec(body);
    if (!col) return [];
    const out = [`ALTER TABLE ${table} ALTER COLUMN ${ident(col[1])} ADD GENERATED BY DEFAULT AS IDENTITY;`];
    stats.identities++;
    if (next) {
      out.push(`ALTER TABLE ${table} ALTER COLUMN ${ident(col[1])} RESTART WITH ${next[1]};`);
    }
    return [out.join('\n')];
  }

  const out = [];
  for (const clause of splitAlterClauses(body)) {
    if (/^ADD\s+PRIMARY\s+KEY/i.test(clause)) {
      stats.primaryKeys++;
      out.push(`ALTER TABLE ${table} ADD ${deBacktick(clause.replace(/^ADD\s+/i, ''))};`);
      continue;
    }

    const uniqueKey = /^ADD\s+UNIQUE\s+KEY\s+`?([^`\s(]+)`?\s*(\(.*\))$/i.exec(clause);
    if (uniqueKey) {
      const name = ident(uniqueKey[1]);
      const cols = deBacktick(uniqueKey[2]);
      const key = `${table}::u::${cols}`;
      if (seenIndexes.has(key)) {
        warn(`FIX-4 aplicado: UNIQUE duplicado omitido en ${table} (${cols})`);
        continue;
      }
      seenIndexes.add(key);
      seenIndexes.add(`${table}::k::${cols}`);
      stats.unique++;
      const cname = /^(unique_|idx_|fk_)/.test(name) ? name : `unique_${table}_${name}`;
      out.push(`ALTER TABLE ${table} ADD CONSTRAINT ${cname} UNIQUE ${cols};`);
      continue;
    }

    const plainKey = /^ADD\s+KEY\s+`?([^`\s(]+)`?\s*(\(.*\))$/i.exec(clause);
    if (plainKey) {
      const name = ident(plainKey[1]);
      const cols = deBacktick(plainKey[2]);
      const key = `${table}::k::${cols}`;
      if (seenIndexes.has(key)) {
        warn(`FIX-4 aplicado: índice duplicado omitido en ${table} (${cols})`);
        continue;
      }
      seenIndexes.add(key);
      stats.indexes++;
      out.push(`CREATE INDEX ${name} ON ${table} ${cols};`);
      continue;
    }

    const fk = /^ADD\s+CONSTRAINT\s+`?([^`\s]+)`?\s+FOREIGN\s+KEY\s*\(`?([^`)]+)`?\)\s*REFERENCES\s+`?([^`\s(]+)`?\s*\(`?([^`)]+)`?\)(.*)$/i.exec(
      clause
    );
    if (fk) {
      const fkName = ident(fk[1]);
      const childCol = ident(fk[2]);
      const parent = ident(fk[3]);
      const parentCol = ident(fk[4]);
      const actions = fk[5].replace(/\s+/g, ' ').trim();

      const key = `${table}::${childCol}`;
      if (seenFks.has(key)) {
        warn(
          `FIX-3 aplicado: FK duplicada omitida en ${table}.${childCol} -> ${parent}.${parentCol} (${actions || 'sin acciones'})`
        );
        continue;
      }
      seenFks.add(key);
      stats.foreignKeys++;
      out.push(
        `ALTER TABLE ${table} ADD CONSTRAINT ${fkName} FOREIGN KEY (${childCol}) ` +
          `REFERENCES ${parent} (${parentCol})${actions ? ' ' + actions : ''};`
      );
      continue;
    }

    warn(`Cláusula ALTER no reconocida en ${table}: ${clause.slice(0, 70)}`);
  }
  return out;
}

/* ------------------------------------------------------------------ *
 * main
 * ------------------------------------------------------------------ */

function main() {
  if (!fs.existsSync(SRC)) {
    console.error(`❌ No se encontró ${SRC}`);
    process.exit(1);
  }

  const raw = fs.readFileSync(SRC, 'utf8');
  // El dump define un PROCEDURE con DELIMITER $$ (no existe en PostgreSQL).
  const withoutProcedure = raw.replace(/DELIMITER\s+\$\$[\s\S]*?DELIMITER\s*;/g, '');

  const statements = splitStatements(withoutProcedure);
  const tables = [];
  const inserts = [];
  const post = [];

  for (const stmt of statements) {
    const s = stmt.trim();
    if (!s) continue;

    if (/^(SET|START\s+TRANSACTION|COMMIT|USE|LOCK|UNLOCK|DELIMITER|DROP)\b/i.test(s)) {
      stats.skipped.push(s.split(/\s+/).slice(0, 2).join(' '));
      continue;
    }
    if (/^CREATE\s+TABLE/i.test(s)) {
      const converted = convertCreateTable(s);
      if (converted) tables.push(converted);
      continue;
    }
    if (/^INSERT\s+INTO/i.test(s)) {
      const converted = convertInsert(s);
      if (converted) inserts.push(converted);
      continue;
    }
    if (/^ALTER\s+TABLE/i.test(s)) {
      post.push(...convertAlter(s));
      continue;
    }
    warn(`Sentencia no reconocida: ${s.slice(0, 70)}`);
  }

  // ON UPDATE CURRENT_TIMESTAMP -> trigger BEFORE UPDATE (PostgreSQL no lo soporta en la columna)
  const triggers = onUpdateColumns.map(({ table, column }) => {
    const fn = `${table}_${column}_touch`;
    return (
      `CREATE OR REPLACE FUNCTION ${fn}() RETURNS trigger AS $$\n` +
      `BEGIN\n  NEW.${column} = CURRENT_TIMESTAMP;\n  RETURN NEW;\nEND;\n$$ LANGUAGE plpgsql;\n\n` +
      `CREATE TRIGGER trg_${fn}\n  BEFORE UPDATE ON ${table}\n  FOR EACH ROW EXECUTE FUNCTION ${fn}();`
    );
  });

  const header = [
    '-- ============================================================',
    '-- PostgreSQL — Esquema generado automáticamente desde el dump MySQL/MariaDB',
    `-- Origen : database/lasmunecasderamon.sql`,
    `-- Generado: ${new Date().toISOString().slice(0, 19).replace('T', ' ')}`,
    '-- Script : scripts/mysql-to-postgres.mjs',
    '--',
    '-- NO editar a mano. Regenerar con:  node scripts/mysql-to-postgres.mjs',
    '-- ============================================================',
    ''
  ].join('\n');

  const body = [
    'BEGIN;',
    '',
    tables.join('\n\n'),
    '',
    inserts.join('\n\n'),
    '',
    post.join('\n'),
    '',
    triggers.join('\n\n'),
    '',
    'COMMIT;',
    ''
  ].join('\n');

  console.log('📊 Informe de conversión');
  console.log('──────────────────────────────────────────────');
  for (const [k, v] of Object.entries(stats)) {
    if (k === 'skipped') continue;
    console.log(`  ${k.padEnd(14)} ${v}`);
  }
  if (stats.skipped.length) {
    const uniq = [...new Set(stats.skipped)];
    console.log(`  Omitidas       ${stats.skipped.length} (${uniq.join(', ')})`);
  }
  console.log(`  triggers       ${onUpdateColumns.length}`);

  if (warnings.length) {
    console.log('\n⚠️  Avisos:');
    for (const w of warnings) console.log(`   - ${w}`);
  }

  if (!REPORT_ONLY) {
    fs.writeFileSync(OUT, header + body, 'utf8');
    console.log(`\n✅ Escrito ${path.relative(process.cwd(), OUT)} (${(header + body).length} bytes)`);
  } else {
    console.log('\n(--report: no se escribió ningún archivo)');
  }
}

main();
